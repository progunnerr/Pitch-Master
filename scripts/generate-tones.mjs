import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { frequency } from '../src/domain/musicTheory/index.ts';

const directory = fileURLToPath(new URL('../assets/audio/', import.meta.url));
mkdirSync(directory, { recursive: true });
const sampleRate = 24000;
const duration = 1.3;
const sampleCount = Math.round(sampleRate * duration);
const entries = [];

for (let octave = 3; octave <= 6; octave++) {
  for (let pitch = 0; pitch < 12; pitch++) {
    const midi = (octave + 1) * 12 + pitch;
    const hz = frequency(pitch, octave);
    const wav = Buffer.alloc(44 + sampleCount * 2);
    wav.write('RIFF', 0);
    wav.writeUInt32LE(wav.length - 8, 4);
    wav.write('WAVE', 8);
    wav.write('fmt ', 12);
    wav.writeUInt32LE(16, 16);
    wav.writeUInt16LE(1, 20);
    wav.writeUInt16LE(1, 22);
    wav.writeUInt32LE(sampleRate, 24);
    wav.writeUInt32LE(sampleRate * 2, 28);
    wav.writeUInt16LE(2, 32);
    wav.writeUInt16LE(16, 34);
    wav.write('data', 36);
    wav.writeUInt32LE(sampleCount * 2, 40);
    for (let i = 0; i < sampleCount; i++) {
      const t = i / sampleRate;
      const envelope =
        Math.min(1, t / 0.008) * Math.min(1, (duration - t) / 0.09) * Math.exp(-2.4 * t);
      const phase = 2 * Math.PI * hz * t;
      const tone =
        (Math.sin(phase) + 0.18 * Math.sin(phase * 2) + 0.06 * Math.sin(phase * 3)) / 1.24;
      wav.writeInt16LE(Math.round(tone * envelope * 0.75 * 32767), 44 + i * 2);
    }
    writeFileSync(`${directory}/${midi}.wav`, wav);
    entries.push(`  ${midi}: require('../../../assets/audio/${midi}.wav'),`);
  }
}

writeFileSync(
  new URL('../src/features/audio/toneAssets.ts', import.meta.url),
  `// Generated by scripts/generate-tones.mjs. Static imports let Metro bundle every tone offline.\nexport const TONE_ASSETS: Record<number, number> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`Generated ${entries.length} equal-tempered tones at A4 = 440 Hz.`);
