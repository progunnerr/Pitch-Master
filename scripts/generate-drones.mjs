import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { frequency } from '../src/domain/musicTheory/index.ts';
import { createDroneLoop } from '../src/features/audio/droneWave.ts';

const directory = fileURLToPath(new URL('../assets/audio/drones/', import.meta.url));
mkdirSync(directory, { recursive: true });
const entries = [];
for (let octave = 3; octave <= 5; octave++) {
  for (let pitch = 0; pitch < 12; pitch++) {
    const midi = (octave + 1) * 12 + pitch;
    const { samples, sampleRate } = createDroneLoop(frequency(pitch, octave));
    const wav = Buffer.alloc(44 + samples.length * 2);
    wav.write('RIFF', 0);
    wav.writeUInt32LE(wav.length - 8, 4);
    wav.write('WAVE', 8);
    wav.write('fmt ', 12);
    wav.writeUInt32LE(16, 16);
    wav.writeUInt16LE(1, 20);
    wav.writeUInt16LE(1, 22);
    wav.writeUInt32LE(sampleRate, 24);
    wav.writeUInt32LE(sampleRate * 2, 28);
    wav.writeUInt16LE(2, 32);
    wav.writeUInt16LE(16, 34);
    wav.write('data', 36);
    wav.writeUInt32LE(samples.length * 2, 40);
    for (let frame = 0; frame < samples.length; frame++)
      wav.writeInt16LE(Math.round(samples[frame] * 32767), 44 + frame * 2);
    writeFileSync(`${directory}/${midi}.wav`, wav);
    entries.push(`  ${midi}: require('../../../assets/audio/drones/${midi}.wav'),`);
  }
}
writeFileSync(
  new URL('../src/features/audio/droneAssets.ts', import.meta.url),
  `// Generated by scripts/generate-drones.mjs. Every drone is bundled for offline use.\nexport const DRONE_ASSETS: Record<number, number> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`Generated ${entries.length} phase-matched tonic loops.`);
